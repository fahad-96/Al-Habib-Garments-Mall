const stockFor = (sizes, pattern = "mid") => {
  const out = {};
  sizes.forEach((s, i) => {
    if (pattern === "low") out[s] = i % 3 === 0 ? 1 : i % 3 === 1 ? 2 : 0;
    else if (pattern === "one-out") out[s] = i === Math.floor(sizes.length / 2) ? 0 : 4 + (i % 3);
    else if (pattern === "high") out[s] = 8 + (i % 4);
    else out[s] = 3 + (i % 4);
  });
  return out;
};

const V = (color, stockPattern = "mid") => ({ color, hex: COLORS[color] || "#999999", stockPattern });

