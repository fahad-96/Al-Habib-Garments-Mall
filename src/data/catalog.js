let sortCounter = 0;
const P = ({ variants, sizes, views = 3, art, ...rest }) => {
  const category = getCategory(rest.categoryKey);
  const sizeSet = rest.sizeSet || category?.sizeSet || "apparel";
  const offered = sizes || SIZE_SETS[sizeSet].sizes;
  sortCounter += 10;
  return {
    id: `dummy-${rest.slug}`,
    brand: "Al Habib",
    badge: "",
    tags: [],
    details: {},
    shortInfo: "",
    description: "",
    sortOrder: sortCounter,
    isActive: true,
    createdAt: "2026-09-01T00:00:00.000Z",
    ...rest,
    department: rest.department || category?.department || "men",
    sizeSet,
    sizes: offered,
    art: art || { pattern: "solid", glyph: "shirt" },
    variants: variants.map((v) => ({
      color: v.color,
      hex: v.hex,
      images: Array.from({ length: views }, (_, i) => `/image/products/${rest.slug}/${slugifyColor(v.color)}-${i + 1}.svg`),
      stock: stockFor(offered, v.stockPattern),
    })),
  };
};

